"""Deterministic runtime identity for unpacked and packaged builds (no Git required)."""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_DIRS = ('assets', 'background', 'content-scripts', 'popup', 'shared', 'sidepanel')

def identity(root=ROOT):
    files = [root / 'manifest.json']
    for directory in RUNTIME_DIRS:
        files.extend(p for p in (root / directory).rglob('*') if p.is_file()
                     and not any(part.startswith('.') for part in p.relative_to(root).parts)
                     and p != root / 'shared/build.js')
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(path.relative_to(root).as_posix().encode() + b'\0' + path.read_bytes() + b'\0')
    return digest.hexdigest()[:16]

def source(root=ROOT):
    version = json.loads((root / 'manifest.json').read_text())['version']
    return '// Generated by scripts/build-id.py; regenerate after runtime changes.\n' + 'globalThis.StudyBuild=Object.freeze(' + json.dumps({'version': version, 'id': identity(root)}, separators=(',', ':')) + ');\n'

if __name__ == '__main__':
    path = ROOT / 'shared/build.js'
    expected = source()
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit('Runtime build identity is stale. Run python3 scripts/build-id.py.')
    else:
        path.write_text(expected)
    print('Build identity: ' + identity())
